def main() -> int:
    SAMPLES.mkdir(parents=True, exist_ok=True)
    created: list[str] = []
    skipped: list[str] = []
    for name, content in FILES.items():
        path = SAMPLES / name
        if path.exists():
            skipped.append(name)
            continue
        path.write_text(content, encoding="utf-8")
        created.append(name)

    for name in created:
        print(f"Создан: samples/{name}")
    for name in skipped:
        print(f"Пропущен (уже существует): samples/{name}")
    if not created and not skipped:
        print("Ничего не создано.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
